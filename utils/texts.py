def finished_announce(title, winners_lines):
    t = title or "Розіграш"
    return f"🎉 Підсумки: <b>{t}</b>\n" + "\n".join(winners_lines)

def composed_caption(base_text, channels, button_text):
    if channels:
        if len(channels) == 1:
            _, uname = channels[0]
            steps = (
                f"Щоб взяти участь:\n"
                f"1️⃣ Підпишіться на Telegram-канал: {uname}\n"
                f"2️⃣ Натисніть кнопку «{button_text or 'Беру участь!'}» під цим постом."
            )
        else:
            list_str = "\n".join([f"• {uname}" for _, uname in channels])
            steps = (
                "Щоб взяти участь:\n"
                "1️⃣ Підпишіться на Telegram-канали:\n"
                f"{list_str}\n"
                f"2️⃣ Натисніть кнопку «{button_text or 'Беру участь!'}» під цим постом."
            )
        return f"{base_text}\n\n{steps}"
    return base_text
