def finished_announce(title, winners_lines):
    t = title or "Розыгрыш"
    return f"🎉 Итоги: <b>{t}</b>\n" + "\n".join(winners_lines)

def composed_caption(base_text, channels_block):
    if channels_block:
        return f"{base_text}\n\n<b>Для участия подпишитесь на каналы:</b>\n{channels_block}"
    return base_text
